export function getCategorie(slug){
    return categorii.find((categorie) => categorie.slug === slug);
}

export function getProduseDinCategorie(slug){
    return produseMagazin.filter((produs) => produs.categorie === slug);
}

export function getProdusDinCategorie(categorieSlug, produsSlug){
    return produseMagazin.find(
        (produs) => produs.categorie === categorieSlug && produs.slug === produsSlug
    );
}
